def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for svc in SERVICES:
        (OUT / f"{svc[0]}.yaml").write_text(render(*svc), encoding="utf-8", newline="\n")
    # kustomize cannot load files outside its tree: keep the DB provisioning script in sync
    script = Path(__file__).resolve().parent.parent / "docker" / "postgres" / "init-databases.sh"
    (OUT.parent / "infra").mkdir(parents=True, exist_ok=True)
    (OUT.parent / "infra" / "init-databases.sh").write_text(script.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    print(f"Generated {len(SERVICES)} service manifests in {OUT}")


if __name__ == "__main__":
    main()
